"""Generate a printable Word questionnaire from the app's live instrument items."""
from __future__ import annotations

import re
from pathlib import Path

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.table import WD_CELL_VERTICAL_ALIGNMENT, WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

from config import PROJECT_ROOT, SRC_DATA_DIR, IPC_LABELS, WORKLOAD_LABELS
from instruments import ipc_items, subscales, workload_items

OUT_DIR = PROJECT_ROOT / "documents"
OUT_FILE = OUT_DIR / "UNIOSUNTH_Research_Questionnaire.docx"
CHECKBOX = "\u2610"

STUDY_TITLE = (
    "Development and Use of a Simple Digital Tool for Assessing the Relationship "
    "Between Nursing Workload and Infection Prevention Compliance Among Nurses "
    "in Medical Wards of UNIOSUNTH"
)

WARD_ENTRY = re.compile(
    r"\{\s*name:\s*'(?P<name>(?:[^'\\]|\\.)*)'\s*,\s*group:\s*'(?P<group>(?:[^'\\]|\\.)*)'\s*\}"
)


def shade_cell(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def set_cell_text(cell, text: str, *, bold: bool = False, size: int = 9) -> None:
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if text == CHECKBOX else WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def add_page_number_footer(doc: Document) -> None:
    footer = doc.sections[0].footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = footer.add_run("UNIOSUNTH Nursing Research Tool - Paper Questionnaire")
    run.font.size = Pt(8)
    run.font.color.rgb = RGBColor(90, 90, 90)


def parse_wards() -> list[tuple[str, str]]:
    source = (SRC_DATA_DIR / "wards.ts").read_text(encoding="utf-8")
    return [(m.group("group"), m.group("name")) for m in WARD_ENTRY.finditer(source)]


def grouped_wards() -> dict[str, list[str]]:
    groups: dict[str, list[str]] = {}
    for group, name in parse_wards():
        groups.setdefault(group, []).append(name)
    return groups


def style_document(doc: Document) -> None:
    section = doc.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE
    section.page_width, section.page_height = section.page_height, section.page_width
    section.top_margin = Inches(0.55)
    section.bottom_margin = Inches(0.55)
    section.left_margin = Inches(0.55)
    section.right_margin = Inches(0.55)

    styles = doc.styles
    styles["Normal"].font.name = "Aptos"
    styles["Normal"].font.size = Pt(9)
    styles["Title"].font.name = "Aptos Display"
    styles["Title"].font.size = Pt(20)
    styles["Title"].font.bold = True
    styles["Heading 1"].font.name = "Aptos Display"
    styles["Heading 1"].font.size = Pt(15)
    styles["Heading 1"].font.bold = True
    styles["Heading 2"].font.name = "Aptos Display"
    styles["Heading 2"].font.size = Pt(12)
    styles["Heading 2"].font.bold = True


def add_title(doc: Document) -> None:
    title = doc.add_paragraph()
    title.style = doc.styles["Title"]
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title.add_run("UNIOSUNTH Nursing Research Questionnaire")

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run(STUDY_TITLE)
    run.font.size = Pt(10)
    run.italic = True

    note = doc.add_paragraph()
    note.alignment = WD_ALIGN_PARAGRAPH.CENTER
    note.add_run(
        "Paper version of the software instrument. Tick one box for each applicable option."
    ).font.size = Pt(9)


def add_demographics(doc: Document) -> None:
    doc.add_heading("Section A: Participant Information", level=1)
    doc.add_paragraph(
        "Do not write the participant's name. Use the anonymous nurse code generated by the study coordinator/software."
    )

    info = doc.add_table(rows=5, cols=4)
    info.alignment = WD_TABLE_ALIGNMENT.CENTER
    info.style = "Table Grid"
    rows = [
        ("Nurse code", "__________________", "Date", "____ / ____ / ______"),
        ("Years of experience", "________ years", "Patients this shift", "________"),
        ("Current shift", f"{CHECKBOX} Morning    {CHECKBOX} Afternoon    {CHECKBOX} Night", "", ""),
        ("Highest nursing qualification", f"{CHECKBOX} RN    {CHECKBOX} BNSc    {CHECKBOX} RN+BNSc    {CHECKBOX} MSc    {CHECKBOX} PhD", "", ""),
        ("Ward / Unit", "Tick one ward below", "", ""),
    ]
    for row, values in zip(info.rows, rows):
        for cell, value in zip(row.cells, values):
            set_cell_text(cell, value, bold=value in {values[0], values[2]}, size=9)
        shade_cell(row.cells[0], "EAF2F8")
        shade_cell(row.cells[2], "EAF2F8")
        if not values[2]:
            row.cells[1].merge(row.cells[3])

    ward_table = doc.add_table(rows=1, cols=3)
    ward_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    ward_table.style = "Table Grid"
    for idx, heading in enumerate(["Service area", "Ward / Unit", "Tick"]):
        set_cell_text(ward_table.rows[0].cells[idx], heading, bold=True)
        shade_cell(ward_table.rows[0].cells[idx], "D9EAF7")

    for group, wards in grouped_wards().items():
        for ward in wards:
            row = ward_table.add_row().cells
            set_cell_text(row[0], group, size=8)
            set_cell_text(row[1], ward, size=8)
            set_cell_text(row[2], CHECKBOX, size=11)


def add_scale_table(doc: Document, *, title: str, instruction: str, labels: dict[int, str], items) -> None:
    doc.add_page_break()
    doc.add_heading(title, level=1)
    doc.add_paragraph(instruction)

    legend = "    ".join(f"{key} = {label}" for key, label in labels.items())
    legend_para = doc.add_paragraph()
    legend_para.add_run("Response options: ").bold = True
    legend_para.add_run(legend)

    if any(item.reversed for item in items):
        doc.add_paragraph("Items marked (R) are reverse-scored during analysis.")

    for subscale in subscales(items):
        doc.add_heading(subscale, level=2)
        cols = 2 + len(labels)
        table = doc.add_table(rows=1, cols=cols)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.style = "Table Grid"
        headers = ["No.", "Statement"] + [f"{key}\n{label}" for key, label in labels.items()]
        for idx, header in enumerate(headers):
            set_cell_text(table.rows[0].cells[idx], header, bold=True, size=8)
            shade_cell(table.rows[0].cells[idx], "D9EAF7")

        for item in [i for i in items if i.subscale == subscale]:
            row = table.add_row().cells
            set_cell_text(row[0], str(item.id), bold=True, size=8)
            suffix = " (R)" if item.reversed else ""
            set_cell_text(row[1], f"{item.text}{suffix}", size=8)
            for cell in row[2:]:
                set_cell_text(cell, CHECKBOX, size=11)

        for row in table.rows:
            row.cells[0].width = Inches(0.35)
            row.cells[1].width = Inches(5.1)
            for cell in row.cells[2:]:
                cell.width = Inches(0.85)


def main() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    doc = Document()
    style_document(doc)
    add_page_number_footer(doc)
    add_title(doc)
    add_demographics(doc)
    add_scale_table(
        doc,
        title="Section B: Nursing Workload Scale",
        instruction=(
            "Rate how each statement applied to your work during your most recent completed shift. "
            "Select one response per item."
        ),
        labels=WORKLOAD_LABELS,
        items=workload_items(),
    )
    add_scale_table(
        doc,
        title="Section C: IPC Compliance Scale (CSPS)",
        instruction=(
            "How often do you perform each infection prevention practice in your current nursing work? "
            "Select the most accurate response per item."
        ),
        labels=IPC_LABELS,
        items=ipc_items(),
    )
    doc.save(OUT_FILE)
    print(OUT_FILE)


if __name__ == "__main__":
    main()
